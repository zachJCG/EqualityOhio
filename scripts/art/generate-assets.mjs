#!/usr/bin/env node
/*
 * Regenerates every generated brand asset from source.
 *
 *   npm run assets              everything
 *   npm run assets -- icons og  only the named steps (icons, og, images, textures)
 *
 * Sources: the palette in public/css/eo-brand-tokens.css (read by kit.mjs),
 * the official logo PNG (measured by mark.mjs), the self-hosted woff2 fonts
 * (unpacked by fonts.mjs), each card's page under public/ (og.mjs), and the
 * two original images in public/assets/img (images.mjs).
 *
 * Outputs (all committed; librsvg and fontconfig can differ between
 * machines, so the PNGs are build products we check in rather than
 * regenerate on deploy):
 *   public/favicon.svg, public/favicon.ico, public/apple-touch-icon.png
 *   public/assets/brand/{icon-192,icon-512,icon-maskable-512}.png, mark.svg
 *   public/assets/og/<key>.png              share cards, 1200x630
 *   scripts/art/og-cards.json              card paths + alt text for the head generator
 *   public/assets/textures/{hero,band}-bars.svg
 *   public/assets/img/<slug>-<w>.{avif,webp,png}
 *
 * Deterministic and idempotent: the same inputs give the same bytes, and a
 * file is only rewritten when its bytes change (a second run reports
 * "0 changed").
 *
 * EO_ART_DEBUG=<dir> also writes each share card's SVG source there.
 */
import { join } from "node:path";

import { ROOT, writePublic, writtenReport } from "./kit.mjs";
import { registerBrandFonts } from "./fonts.mjs";

const ALL = ["icons", "og", "images", "textures"];
const args = process.argv.slice(2).filter((a) => !a.startsWith("-"));
const steps = args.length ? args : ALL;
for (const s of steps) if (!ALL.includes(s)) throw new Error(`unknown step "${s}" (expected: ${ALL.join(", ")})`);

// Fonts first: fontconfig reads FONTCONFIG_FILE on first use.
if (steps.includes("og")) await registerBrandFonts();
const sharp = (await import("sharp")).default;
// One thread per operation keeps encoder output byte-stable across runs.
sharp.concurrency(1);

const summary = {};

if (steps.includes("textures")) {
  const { buildTextures } = await import("./textures.mjs");
  buildTextures();
}

if (steps.includes("icons")) {
  const { buildIcons } = await import("./icons.mjs");
  summary.icons = await buildIcons(sharp);
}

if (steps.includes("og")) {
  const { buildOgCards } = await import("./og.mjs");
  const cards = await buildOgCards(sharp);
  const json = {
    $comment:
      "Generated by scripts/art/generate-assets.mjs (npm run assets). Share-card image, size and alt text per card key. votersguide uses the scorecard banner as its card.",
    ...cards,
    votersguide: {
      image: "/assets/img/candidate-scorecard-2026-banner.png",
      width: 1250,
      height: 625,
      type: "image/png",
      alt: "2026 Candidate Scorecard. See how candidates measure up on the issues that matter for LGBTQ+ Ohioans and their families. Equality Ohio.",
      source: "public/votersguide.html",
    },
  };
  writePublic("og-cards.json", JSON.stringify(json, null, 2) + "\n", join(ROOT, "scripts", "art"));
  summary.og = cards;
}

if (steps.includes("images")) {
  const { buildImages } = await import("./images.mjs");
  summary.images = await buildImages(sharp);
}

/* --------------------------------------------------------------- report */

const rows = writtenReport();
const changed = rows.filter((r) => r.changed).length;
const kb = (b) => `${(b / 1024).toFixed(1)} KB`;
console.log(`Generated assets (${rows.length} files, ${changed} changed):`);
for (const r of rows) console.log(`  ${r.changed ? "*" : " "} ${r.path.padEnd(58)} ${kb(r.bytes).padStart(9)}`);
if (summary.icons) {
  const m = summary.icons.mark;
  console.log(`\nLogomark measured from ${m.source.file}: ${m.w} x ${m.h} logo px, bars:`);
  for (const r of m.rects) console.log(`  ${r.token.padEnd(6)} x=${r.x} y=${r.y} w=${r.w} h=${r.h} (pixel rgb ${r.measured.join(",")})`);
}
if (summary.og) {
  console.log(`\nShare cards:`);
  for (const [k, c] of Object.entries(summary.og)) console.log(`  ${k.padEnd(13)} ${String(c.headlineSize).padStart(3)}px  ${c.headline}`);
}
if (summary.images) {
  const { pictureSnippet } = await import("./images.mjs");
  console.log(`\nImages:`);
  for (const im of summary.images) {
    console.log(`  ${im.src} ${im.original.width}x${im.original.height} ${kb(im.original.bytes)}`);
    for (const f of im.files) console.log(`    ${f.path.padEnd(52)} ${`${f.width}x${f.height}`.padStart(9)} ${kb(f.bytes).padStart(9)}`);
  }
  for (const im of summary.images) {
    if (im.usage) console.log(`\n<picture> for ${im.usage.page}:\n${pictureSnippet(im, im.usage)}`);
  }
}
