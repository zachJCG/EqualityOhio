#!/usr/bin/env node
/**
 * scripts/build-pages.mjs
 * -----------------------
 * Writes the generated regions into every static page under public/.
 *
 *   npm run pages:build     rewrite the pages
 *   npm run check:pages     exit 1 on any drift or registry problem (CI)
 *
 * Regions (everything between the markers is rebuilt on every run, so it is
 * safe to run repeatedly and pointless to edit by hand):
 *
 *   <head>   <!-- seo:start --> ... <!-- seo:end -->, directly after the
 *            charset and viewport metas. Holds everything else the head
 *            needs: robots, title, description, canonical (launched only),
 *            og:*, twitter:*, theme-color, icons, manifest, font preloads,
 *            the three site stylesheets and JSON-LD. From lib/seo.mjs.
 *   <body>   <!-- chrome:header:start --> ... <!-- chrome:header:end -->, the
 *            first thing in <body>: skip link, preview ribbon, equality bar
 *            and <header>, as direct children of <body> so the sticky header
 *            is bounded by the body. From lib/chrome.mjs.
 *            <!-- chrome:footer:start --> ... <!-- chrome:footer:end -->, where
 *            the page had <div data-site-footer></div> (or after </main>):
 *            the phone help bar on lib/chrome.mjs HELP_BAR_PAGES, then the
 *            <footer>.
 *
 * public/gate.html gets the seo region but no chrome.
 *
 * A new page needs only: charset + viewport metas, the empty seo marker pair
 * in <head>, <body data-page="...">, the empty chrome header and footer marker
 * pairs, <main id="main">, and the eo-site-template.js script tag. The old
 * <div data-site-header></div> / <div data-site-footer></div> mounts are
 * still accepted and are replaced on the first run.
 *
 * Outside the regions, the generator removes only tags it owns (title, the
 * description/robots/theme-color metas, og:/twitter: metas, canonical, icon,
 * apple-touch-icon and manifest links, font preloads, the three site
 * stylesheets, JSON-LD) so a hand-added duplicate cannot linger. Page-scoped
 * <style> blocks and anything else stay where they are.
 *
 * --check also validates the registry: every page has an entry and every
 * entry a file, titles are unique, descriptions are present and at most 160
 * characters, share images / icons / stylesheets / preloaded fonts exist on
 * disk, every page has exactly one <h1>, one <main id="main">, a known
 * data-page id, no heading that skips a level (an h3 straight after the h1,
 * say; promote it and keep its look with a class), and no inline executable
 * script or inline event handler (the static pages are served with
 * script-src 'self').
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { KNOWN_PAGE_IDS, footerHTML, headerHTML } from '../lib/chrome.mjs';
import {
  FONT_PRELOADS,
  ICONS,
  LAUNCHED,
  MANIFEST_ICONS,
  NOT_FOUND,
  OG_IMAGES,
  OG_SITE_NAME,
  PAGES,
  SCORECARD_BANNER,
  STYLESHEETS,
  THEME_COLOR,
  absolute,
  imageFor,
  jsonLdFor,
  pageFor,
  robotsContent,
} from '../lib/seo.mjs';
import { PUBLIC_DIR, ROOT, cleanUrlFor, staticPages } from '../lib/static-pages.mjs';

export const SEO_START = '<!-- seo:start -->';
export const SEO_END = '<!-- seo:end -->';
export const HEADER_START = '<!-- chrome:header:start -->';
export const HEADER_END = '<!-- chrome:header:end -->';
export const FOOTER_START = '<!-- chrome:footer:start -->';
export const FOOTER_END = '<!-- chrome:footer:end -->';

/* Pages that carry the seo region but no site chrome. */
const NO_CHROME = new Set(['/gate']);

const MAX_DESCRIPTION = 160;

const esc = (value) =>
  String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

/* JSON inside <script>: "<" is escaped so no value can close the element. */
const jsonForScript = (value) => JSON.stringify(value, null, 2).replace(/</g, '\\u003c');

/* ---------------------------------------------------------------------------
 * Region content
 * ------------------------------------------------------------------------- */

/** The lines of the seo region (without markers or indentation). */
export function headLines(page) {
  const img = imageFor(page);
  const lines = [];
  const meta = (attr, key, content) => lines.push(`<meta ${attr}="${key}" content="${esc(content)}" />`);

  lines.push('<!-- Generated by `npm run pages:build` from lib/seo.mjs. Do not edit; change the registry. -->');
  meta('name', 'robots', robotsContent(page));
  lines.push(`<title>${esc(page.title)}</title>`);
  meta('name', 'description', page.description);
  if (LAUNCHED && !page.noindex) lines.push(`<link rel="canonical" href="${esc(absolute(page.url))}" />`);

  meta('property', 'og:type', page.type || 'website');
  meta('property', 'og:site_name', OG_SITE_NAME);
  meta('property', 'og:locale', 'en_US');
  meta('property', 'og:title', page.ogTitle || page.title);
  meta('property', 'og:description', page.ogDescription || page.description);
  meta('property', 'og:url', absolute(page.url));
  meta('property', 'og:image', absolute(img.path));
  meta('property', 'og:image:width', String(img.width));
  meta('property', 'og:image:height', String(img.height));
  meta('property', 'og:image:alt', img.alt);

  meta('name', 'twitter:card', 'summary_large_image');
  meta('name', 'twitter:title', page.ogTitle || page.title);
  meta('name', 'twitter:description', page.ogDescription || page.description);
  meta('name', 'twitter:image', absolute(img.path));
  meta('name', 'twitter:image:alt', img.alt);

  meta('name', 'theme-color', THEME_COLOR);
  lines.push(`<link rel="icon" href="${ICONS.ico}" sizes="32x32" />`);
  lines.push(`<link rel="icon" href="${ICONS.svg}" type="image/svg+xml" />`);
  lines.push(`<link rel="apple-touch-icon" href="${ICONS.appleTouch}" />`);
  lines.push(`<link rel="manifest" href="${ICONS.manifest}" />`);

  for (const font of FONT_PRELOADS) {
    lines.push(`<link rel="preload" href="${font}" as="font" type="font/woff2" crossorigin />`);
  }
  for (const sheet of STYLESHEETS) lines.push(`<link rel="stylesheet" href="${sheet}" />`);

  for (const graph of jsonLdFor(page)) {
    lines.push('<script type="application/ld+json">');
    lines.push(...jsonForScript(graph).split('\n'));
    lines.push('</script>');
  }
  return lines;
}

const indentLines = (text, indent) =>
  text
    .split('\n')
    .map((line) => (line ? indent + line : line))
    .join('\n');

const region = (start, end, body, indent) =>
  `${indent}${start}\n${indentLines(body, indent)}\n${indent}${end}`;

/* ---------------------------------------------------------------------------
 * Surgery on an existing document
 * ------------------------------------------------------------------------- */

// A tag's attribute soup, quote aware so a ">" inside a value does not end it.
const ATTRS = '(?:[^>"\']|"[^"]*"|\'[^\']*\')*';
const wholeLine = (pattern, flags = 'gm') => new RegExp(`^[ \\t]*${pattern}[ \\t]*\\r?\\n?`, flags);
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const regionRe = (start, end) => wholeLine(`${escRe(start)}[\\s\\S]*?${escRe(end)}`, 'm');

const MANAGED_META = /(?:name|property)\s*=\s*["'](?:description|robots|googlebot|theme-color|og:[\w:]+|twitter:[\w:]+)["']/i;
const MANAGED_LINK = /rel\s*=\s*["'](?:canonical|icon|shortcut icon|apple-touch-icon|mask-icon|manifest)["']/i;
const STYLESHEET_HREFS = new Set(STYLESHEETS);
const STALE_COMMENTS = /^[ \t]*<!--\s*(?:MOCKUP|STAGING)\b[^>]*-->[ \t]*\r?\n?/gim;

function isManagedLink(tag) {
  if (MANAGED_LINK.test(tag)) return true;
  const href = (tag.match(/href\s*=\s*["']([^"']*)["']/i) || [])[1] || '';
  if (/rel\s*=\s*["']stylesheet["']/i.test(tag) && STYLESHEET_HREFS.has(href)) return true;
  if (/rel\s*=\s*["']preload["']/i.test(tag) && /as\s*=\s*["']font["']/i.test(tag)) return true;
  return false;
}

function stripManagedHead(head) {
  return head
    .replace(regionRe(SEO_START, SEO_END), '')
    .replace(STALE_COMMENTS, '')
    .replace(wholeLine('<title>[\\s\\S]*?<\\/title>'), '')
    .replace(wholeLine(`<script\\s+type=["']application\\/ld\\+json["'][\\s\\S]*?<\\/script>`), '')
    .replace(wholeLine(`<meta\\b${ATTRS}>`), (tag) => (MANAGED_META.test(tag) ? '' : tag))
    .replace(wholeLine(`<link\\b${ATTRS}>`), (tag) => (isManagedLink(tag) ? '' : tag));
}

function applyHead(source, page) {
  const headStart = source.search(/<head\b/i);
  const headEnd = source.search(/<\/head>/i);
  if (headStart === -1 || headEnd === -1) throw new Error('no <head> in document');
  let head = stripManagedHead(source.slice(headStart, headEnd));

  // charset and viewport stay first; the region sits directly below them.
  const viewport = head.match(new RegExp(`^([ \\t]*)<meta\\b${ATTRS}name=["']viewport["']${ATTRS}>[ \\t]*\\r?\\n`, 'm'));
  if (!viewport) throw new Error('no viewport meta to anchor the seo region to');
  const indent = viewport[1] || '    ';
  const at = viewport.index + viewport[0].length;
  head = `${head.slice(0, at)}${region(SEO_START, SEO_END, headLines(page).join('\n'), indent)}\n${head.slice(at)}`;
  return source.slice(0, headStart) + head + source.slice(headEnd);
}

const HEADER_MOUNT = wholeLine('<div\\s+data-site-header(?:="")?\\s*>\\s*<\\/div>', 'm');
const FOOTER_MOUNT = /^([ \t]*)<div\s+data-site-footer(?:="")?\s*>\s*<\/div>[ \t]*$/m;

function bodyIndent(source) {
  const main = source.match(/^([ \t]*)<main\b/m);
  return main ? main[1] : '    ';
}

function applyChrome(source, page, pageId) {
  const indent = bodyIndent(source);
  const wantChrome = !NO_CHROME.has(page.url);

  // Header: remove whatever is there (region or legacy mount), then insert the
  // region as the first thing inside <body>.
  let out = source.replace(regionRe(HEADER_START, HEADER_END), '').replace(HEADER_MOUNT, '');
  if (wantChrome) {
    const body = out.match(new RegExp(`<body\\b${ATTRS}>[ \\t]*\\r?\\n?`, 'i'));
    if (!body) throw new Error('no <body> in document');
    const at = body.index + body[0].length;
    const lead = body[0].endsWith('\n') ? '' : '\n';
    out = `${out.slice(0, at)}${lead}${region(HEADER_START, HEADER_END, headerHTML(pageId), indent)}\n${out.slice(at)}`;
  }

  // Footer: replace the region or the legacy mount in place; otherwise place
  // it right after </main>.
  const footer = wantChrome ? region(FOOTER_START, FOOTER_END, footerHTML(pageId), indent) : '';
  const existing = out.match(new RegExp(`^([ \\t]*)${escRe(FOOTER_START)}[\\s\\S]*?${escRe(FOOTER_END)}[ \\t]*$`, 'm'));
  if (existing) {
    out = wantChrome
      ? out.replace(existing[0], () => footer)
      : out.replace(new RegExp(`${escRe(existing[0])}\\r?\\n?`), '');
  } else if (FOOTER_MOUNT.test(out)) {
    out = wantChrome
      ? out.replace(FOOTER_MOUNT, () => footer)
      : out.replace(new RegExp(`${FOOTER_MOUNT.source}\\r?\\n?`, 'm'), '');
  } else if (wantChrome) {
    const main = out.match(/^[ \t]*<\/main>[ \t]*\r?\n/m);
    if (!main) throw new Error('no footer marker, footer mount or </main> to place the footer after');
    const at = main.index + main[0].length;
    out = `${out.slice(0, at)}${footer}\n${out.slice(at)}`;
  }
  return out;
}

const pageIdOf = (source) => {
  const m = source.match(new RegExp(`<body\\b${ATTRS}>`, 'i'));
  if (!m) return null;
  const id = m[0].match(/data-page\s*=\s*["']([^"']*)["']/i);
  return id ? id[1] : null;
};

/** Rebuild every region in one document's source. */
export function renderSource(source, page) {
  const pageId = pageIdOf(source) || '';
  return applyChrome(applyHead(source, page), page, pageId);
}

/** The fully regenerated content of one page under public/ (pure: no write). */
export function renderFile(absPath) {
  const url = cleanUrlFor(absPath);
  const page = pageFor(url);
  if (!page) throw new Error(`${url} has no entry in lib/seo.mjs PAGES`);
  return renderSource(readFileSync(absPath, 'utf8'), page);
}

/* ---------------------------------------------------------------------------
 * Validation
 * ------------------------------------------------------------------------- */

const publicFile = (urlPath) => join(PUBLIC_DIR, urlPath.replace(/^\//, ''));

/** Registry and page problems, as strings. Empty when everything is right. */
export function validate(pages = staticPages()) {
  const problems = [];
  const onDisk = new Set(pages.map((p) => p.url));

  for (const p of pages) {
    if (!pageFor(p.url)) problems.push(`registry: ${p.file} exists but ${p.url} has no entry in lib/seo.mjs PAGES`);
  }
  for (const entry of PAGES) {
    if (!onDisk.has(entry.url)) problems.push(`registry: ${entry.url} is in lib/seo.mjs PAGES but has no file under public/`);
  }

  const titles = new Map();
  for (const entry of [...PAGES, NOT_FOUND]) {
    const where = `registry ${entry.url}`;
    if (!entry.title || !entry.title.trim()) problems.push(`${where}: no title`);
    else if (titles.has(entry.title)) problems.push(`${where}: duplicate title, same as ${titles.get(entry.title)}`);
    else titles.set(entry.title, entry.url);

    if (!entry.description || !entry.description.trim()) problems.push(`${where}: no description`);
    else if (entry.description.length > MAX_DESCRIPTION) {
      problems.push(`${where}: description is ${entry.description.length} characters (max ${MAX_DESCRIPTION})`);
    }

    const img = imageFor(entry);
    if (!img.alt) problems.push(`${where}: share image has no alt text`);
    if (!existsSync(publicFile(img.path))) problems.push(`${where}: share image missing on disk: public${img.path}`);
  }

  // Share-card metadata must match what the art generator drew.
  const cardsFile = join(ROOT, 'scripts/art/og-cards.json');
  if (existsSync(cardsFile)) {
    const cards = JSON.parse(readFileSync(cardsFile, 'utf8'));
    for (const [key, img] of [...Object.entries(OG_IMAGES), ['votersguide', SCORECARD_BANNER]]) {
      const drawn = cards[key];
      if (!drawn) {
        problems.push(`share cards: "${key}" is in lib/seo.mjs but not in scripts/art/og-cards.json`);
        continue;
      }
      for (const [field, ours, theirs] of [
        ['path', img.path, drawn.image],
        ['width', img.width, drawn.width],
        ['height', img.height, drawn.height],
        ['alt', img.alt, drawn.alt],
      ]) {
        if (ours !== theirs) problems.push(`share cards: "${key}" ${field} is ${JSON.stringify(ours)} in lib/seo.mjs but ${JSON.stringify(theirs)} in scripts/art/og-cards.json`);
      }
    }
  }

  const assets = [
    ['icon', ICONS.ico],
    ['icon', ICONS.svg],
    ['apple-touch-icon', ICONS.appleTouch],
    ...MANIFEST_ICONS.map((i) => ['manifest icon', i.src]),
    ...STYLESHEETS.map((s) => ['stylesheet', s]),
    ...FONT_PRELOADS.map((f) => ['preloaded font', f]),
  ];
  for (const [kind, path] of assets) {
    if (!existsSync(publicFile(path))) problems.push(`assets: ${kind} missing on disk: public${path}`);
  }

  for (const p of pages) {
    const source = readFileSync(p.abs, 'utf8');
    const where = p.file;
    const pageId = pageIdOf(source);
    if (pageId === null) problems.push(`${where}: <body> has no data-page attribute`);
    else if (!KNOWN_PAGE_IDS.has(pageId)) problems.push(`${where}: data-page="${pageId}" is not a known page id (lib/chrome.mjs KNOWN_PAGE_IDS)`);

    if (!/<html\b[^>]*\blang="en"/i.test(source)) problems.push(`${where}: <html> has no lang="en"`);
    const h1s = (source.match(/<h1\b/gi) || []).length;
    if (h1s !== 1) problems.push(`${where}: ${h1s} <h1> elements, want exactly 1`);
    let previous = 0;
    for (const [, level, rest] of source.replace(/<!--[\s\S]*?-->/g, '').matchAll(/<h([1-6])\b([^>]*)>/gi)) {
      const n = Number(level);
      if (previous && n > previous + 1) {
        const cls = (rest.match(/class="([^"]*)"/) || [])[1];
        problems.push(`${where}: <h${n}${cls ? ` class="${cls}"` : ''}> follows an <h${previous}> (heading levels must not skip; promote it and keep its look with a class)`);
      }
      previous = n;
    }
    const mains = (source.match(/<main\b/gi) || []).length;
    if (mains !== 1 || !/<main\b[^>]*\bid="main"/i.test(source)) problems.push(`${where}: want exactly one <main id="main">`);

    for (const [tag] of source.matchAll(new RegExp(`<script\\b${ATTRS}>`, 'gi'))) {
      const external = /\bsrc\s*=/i.test(tag);
      const data = /type\s*=\s*["']application\/(?:ld\+)?json["']/i.test(tag);
      if (!external && !data) problems.push(`${where}: inline <script> (blocked by script-src 'self'; move it to /js/)`);
    }
    for (const [tag] of source.matchAll(new RegExp(`<[a-z][a-z0-9-]*\\b${ATTRS}>`, 'gi'))) {
      if (/\son[a-z]+\s*=/i.test(tag.replace(/"[^"]*"|'[^']*'/g, '""'))) {
        problems.push(`${where}: inline event handler in ${tag.slice(0, 60)}… (blocked by script-src 'self')`);
      }
    }
    if (!NO_CHROME.has(p.url) && !source.includes('src="/js/eo-site-template.js"')) {
      problems.push(`${where}: missing <script src="/js/eo-site-template.js" defer></script>`);
    }
  }
  return problems;
}

/* ------------------------------------------------------------------------ */

function main() {
  const checkOnly = process.argv.includes('--check');
  const pages = staticPages();
  const changed = [];
  const errors = [];

  for (const p of pages) {
    const page = pageFor(p.url);
    if (!page) continue; // reported by validate()
    let next;
    try {
      const source = readFileSync(p.abs, 'utf8');
      next = renderSource(source, page);
      if (next === source) continue;
    } catch (err) {
      errors.push(`${p.file}: ${err.message}`);
      continue;
    }
    changed.push(p.file);
    if (!checkOnly) writeFileSync(p.abs, next);
  }

  const problems = [...errors, ...validate(pages)];
  if (checkOnly && changed.length) {
    problems.push(...changed.map((f) => `${f}: generated regions are out of date; run \`npm run pages:build\``));
  }

  if (!checkOnly) {
    console.log(changed.length
      ? `✓ wrote ${changed.length} of ${pages.length} pages:\n    ${changed.join('\n    ')}`
      : `✓ all ${pages.length} pages already up to date`);
  }
  if (problems.length) {
    console.error(`✗ ${problems.length} problem(s):\n${problems.map((p) => `    ${p}`).join('\n')}`);
    process.exitCode = 1;
  } else if (checkOnly) {
    console.log(`✓ ${pages.length} pages: generated regions current, registry valid (${relative(ROOT, PUBLIC_DIR)}/**/*.html)`);
  }
}

