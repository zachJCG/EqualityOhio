#!/usr/bin/env node
/**
 * Writes the theme's block patterns from the generated page markup:
 *   - one "page layout" pattern per page (patterns/page-<slug>.php), so staff
 *     can insert a whole page's structure;
 *   - one pattern per component, cut from a representative page by the
 *     class on its outermost block (patterns/<component>.php).
 *
 *   node tools/build-patterns.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const CHECK = process.argv.includes('--check');
const pagesDir = join(root, 'plugins/eo-site/content/pages');
const patternsDir = join(root, 'themes/equality-ohio/patterns');
const registry = JSON.parse(readFileSync(join(root, 'plugins/eo-site/data/pages.json'), 'utf8')).pages;

/** The first top-level-or-nested block in `markup` whose opening comment carries `cls` in its className. */
function cutBlock(markup, cls, nth = 0) {
  const re = /<!-- wp:([a-z0-9\/-]+)( \{[^\n]*?\})? (\/)?-->/g;
  let m; let found = -1; let count = 0;
  while ((m = re.exec(markup))) {
    const attrs = m[2] ? JSON.parse(m[2]) : {};
    const classes = (attrs.className || '').split(' ');
    if (classes.includes(cls)) { if (count++ === nth) { found = m.index; break; } }
  }
  if (found === -1) throw new Error(`no block with class ${cls}`);
  // Walk to the matching closer.
  const open = /<!-- wp:([a-z0-9\/-]+)(?: \{[^\n]*?\})? (\/)?-->|<!-- \/wp:([a-z0-9\/-]+) -->/g;
  open.lastIndex = found;
  let depth = 0; let end = -1;
  while ((m = open.exec(markup))) {
    if (m[3]) { depth--; if (depth === 0) { end = m.index + m[0].length; break; } }
    else if (!m[2]) depth++;
    else if (depth === 0) { end = m.index + m[0].length; break; }
  }
  return markup.slice(found, end).trim();
}

const read = (file) => readFileSync(join(pagesDir, file), 'utf8');
const components = [
  ['hero-interior', 'Hero (interior page)', 'give.html', 'hero--interior', 'An eyebrow, the page H1 and a lede. Every interior page starts with one.'],
  ['hero-home', 'Hero (home page)', 'home.html', 'hero', 'The home hero: eyebrow, H1, lede, two buttons and the logo art.'],
  ['section-heading', 'Section heading', 'give.html', 'section__head', 'Eyebrow label plus H2.'],
  ['card-grid-paths', 'Card grid: three paths', 'home.html', 'card-grid--3', 'Three cards with kicker, heading, text and a card link.'],
  ['card-grid-ways-to-give', 'Card grid: four cards', 'give.html', 'card-grid--4', 'Four cards with heading, text and a card link.'],
  ['tier-cards', 'Giving tiers', 'give.html', 'card-grid--3', 'The three giving tiers from /give/.'],
  ['band-cta', 'Purple band with a call to action', 'give.html', 'band', 'Heading, line and a white button on the purple band.'],
  ['band-stats', 'Purple band with statistics', 'home.html', 'band', 'Four number-and-label pairs on the purple band.'],
  ['clinic-callout', 'Legal Clinic callout', 'home.html', 'callout--clinic', 'The clinic callout the phone help bar watches (class clinic-cta).'],
  ['news-cards', 'News cards', 'home.html', 'card-grid--3', 'Three news cards with a colored media area, pill, date, title and link.'],
  ['person-cards', 'People grid', 'about--leadership.html', 'card-grid--3', 'Person cards: initials avatar, name, role.'],
  ['staging-note', 'Staging note', 'give.html', 'eo-staging-note', 'A line that is true only of the preview. Search for eo-staging-note at launch.'],
  ['newsletter-signup', 'Newsletter signup (preview form)', 'home.html', 'form-shell', 'The inline newsletter form. Visual only until it is connected.'],
];
// Some components share a class on the same page; pick the right occurrence.
const nthFor = { 'tier-cards': 0, 'card-grid-ways-to-give': 0, 'news-cards': 1, 'band-cta': 0, 'card-grid-paths': 0, 'person-cards': 0 };

const written = {};
/** Content placeholders become PHP so a pattern resolves on any install. */
function php(content) {
  return content
    .replace(/\{\{THEME_URI\}\}/g, '<?php echo esc_url( get_template_directory_uri() ); ?>')
    .replace(/\{\{DOC:([^}]+)\}\}/g, (_, name) => `<?php echo esc_url( eo_doc_url( '${name}' ) ); ?>`);
}

function pattern(slug, title, description, content, categories, extra = '') {
  content = php(content);
  const file = `<?php
/**
 * Title: ${title}
 * Slug: equality-ohio/${slug}
 * Categories: ${categories}
 * Description: ${description.replace(/\*\//g, '* /')}
${extra} * Generated by tools/build-patterns.mjs. Do not edit.
 */
?>
${content}
`;
  written[`${slug}.php`] = file;
}
for (const [slug, title, file, cls, description] of components) {
  const block = cutBlock(read(file), cls, nthFor[slug] || 0);
  pattern(slug, title, description, block, 'equality-ohio');
}
for (const rec of registry) {
  const slug = `page-${rec.file.replace(/\.html$/, '')}`;
  const content = read(rec.file).trim();
  pattern(slug, `Page layout: ${rec.h1}`, `The full ${rec.path} page as built; insert it to start a page with the same structure.`, content, 'equality-ohio-pages', ` * Block Types: core/post-content\n * Post Types: page\n * Inserter: true\n`);
}

let stale = 0;
for (const [name, content] of Object.entries(written)) {
  const abs = join(patternsDir, name);
  const cur = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  if (cur !== content) { stale++; if (!CHECK) writeFileSync(abs, content); }
}
for (const f of readdirSync(patternsDir)) if (!written[f]) { stale++; if (!CHECK) unlinkSync(join(patternsDir, f)); }
if (CHECK && stale) { console.error(`${stale} pattern file(s) stale: run node tools/build-patterns.mjs`); process.exit(1); }
console.log(`${Object.keys(written).length} patterns (${components.length} components, ${registry.length} page layouts), ${stale} written`);
