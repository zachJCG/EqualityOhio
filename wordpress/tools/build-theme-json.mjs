#!/usr/bin/env node
/**
 * Generates themes/equality-ohio/theme.json from the brand tokens file, so the
 * editor palette and the stylesheet never hold two copies of the colors.
 *
 *   node tools/build-theme-json.mjs          write theme.json
 *   node tools/build-theme-json.mjs --check  exit 1 if theme.json is stale
 *
 * Source of truth: themes/equality-ohio/assets/css/eo-brand-tokens.css (the
 * only file with color literals) and assets/css/eo-fonts list below (the same
 * ten woff2 files the Next.js site self-hosted).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const theme = join(here, '..', 'themes', 'equality-ohio');
const tokens = readFileSync(join(theme, 'assets/css/eo-brand-tokens.css'), 'utf8');

// Every token that is a color literal (hex or rgba) becomes a palette entry.
const palette = [];
const re = /--eo-([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6}|rgba?\([^)]*\))\s*;\s*(?:\/\*\s*([^*]*?)\s*\*\/)?/g;
let m;
while ((m = re.exec(tokens))) {
  const slug = m[1];
  const name = slug.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
  palette.push({ slug: `eo-${slug}`, name: `EO ${name}`, color: m[2] });
}
if (palette.length < 20) throw new Error(`Only ${palette.length} palette colors parsed; check the regex.`);

const gradients = [
  { slug: 'eo-equality-bar', name: 'EO Equality Bar', gradient: 'var(--eo-equality-bar)' },
  { slug: 'eo-policy', name: 'EO Policy Gradient', gradient: 'var(--eo-policy-gradient)' },
];

const faces = (family, list) => list.map(([w, style, file]) => ({
  fontFamily: family, fontWeight: String(w), fontStyle: style, fontDisplay: 'swap',
  src: [`file:./assets/fonts/${file}`],
}));
const fontFamilies = [
  {
    slug: 'eo-body', name: 'Open Sans (body)', fontFamily: "'Open Sans', 'Helvetica Neue', Arial, sans-serif",
    fontFace: faces('Open Sans', [
      [400, 'normal', 'open-sans-latin-400-normal.woff2'],
      [400, 'italic', 'open-sans-latin-400-italic.woff2'],
      [600, 'normal', 'open-sans-latin-600-normal.woff2'],
      [700, 'normal', 'open-sans-latin-700-normal.woff2'],
    ]),
  },
  {
    slug: 'eo-display', name: 'Montserrat (display)', fontFamily: "'Montserrat', 'Helvetica Neue', Arial, sans-serif",
    fontFace: faces('Montserrat', [
      [400, 'normal', 'montserrat-latin-400-normal.woff2'],
      [600, 'normal', 'montserrat-latin-600-normal.woff2'],
      [700, 'normal', 'montserrat-latin-700-normal.woff2'],
      [800, 'normal', 'montserrat-latin-800-normal.woff2'],
    ]),
  },
  {
    slug: 'eo-emphasis', name: 'League Spartan (emphasis)', fontFamily: "'League Spartan', 'Montserrat', Arial, sans-serif",
    fontFace: faces('League Spartan', [
      [600, 'normal', 'league-spartan-latin-600-normal.woff2'],
      [700, 'normal', 'league-spartan-latin-700-normal.woff2'],
    ]),
  },
];

const json = {
  $schema: 'https://schemas.wp.org/trunk/theme.json',
  version: 3,
  // Generated by tools/build-theme-json.mjs from assets/css/eo-brand-tokens.css. Do not edit by hand.
  settings: {
    appearanceTools: false,
    useRootPaddingAwareAlignments: false,
    layout: { contentSize: '1160px', wideSize: '1160px' },
    color: {
      palette, gradients,
      defaultPalette: false, defaultGradients: false, defaultDuotone: false,
      custom: false, customGradient: false, customDuotone: false,
      background: true, text: true, link: false,
    },
    typography: {
      fontFamilies,
      defaultFontSizes: false, customFontSize: false, fluid: false,
      fontSizes: [
        { slug: 'eo-small', name: 'Small', size: '0.82rem' },
        { slug: 'eo-body', name: 'Body', size: '17px' },
        { slug: 'eo-lede', name: 'Lede', size: '1.15rem' },
        { slug: 'eo-h3', name: 'Heading 3', size: '1.25rem' },
      ],
      dropCap: false, fontStyle: false, fontWeight: false, letterSpacing: false,
      lineHeight: false, textDecoration: false, textTransform: false,
    },
    spacing: {
      // No blockGap key on purpose: WordPress then emits no flow-gap rules that
      // would fight eo-site.css paragraph and heading margins (see eo-wp.css).
      padding: false, margin: false, units: ['rem', 'em', 'px', '%'],
    },
    border: { color: false, radius: false, style: false, width: false },
    shadow: { defaultPresets: false },
    custom: {
      // Mirrors of the CSS tokens for editor-side use; the stylesheet is the source.
      navHeight: '76px', maxWidth: '1160px',
      radius: { sm: '6px', md: '10px', lg: '16px' },
    },
    blocks: {
      'core/button': { color: { background: false, text: false } },
    },
  },
  styles: {
    // Intentionally empty: eo-brand-tokens.css + eo-site.css define the look.
    // Setting nothing here keeps WordPress from printing competing body rules.
  },
  templateParts: [
    { name: 'header', title: 'Header', area: 'header' },
    { name: 'footer', title: 'Footer', area: 'footer' },
    { name: 'help-bar', title: 'Legal Clinic help bar', area: 'uncategorized' },
  ],
  customTemplates: [
    { name: 'page-legal-guide', title: 'Legal Clinic guide (with help bar)', postTypes: ['page'] },
  ],
  patterns: [],
};

const out = JSON.stringify(json, null, 2) + '\n';
const target = join(theme, 'theme.json');
if (process.argv.includes('--check')) {
  const cur = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (cur !== out) { console.error('theme.json is stale: run node tools/build-theme-json.mjs'); process.exit(1); }
  console.log('theme.json is current');
} else {
  writeFileSync(target, out);
  console.log(`theme.json written: ${palette.length} palette colors, ${fontFamilies.length} font families`);
}
